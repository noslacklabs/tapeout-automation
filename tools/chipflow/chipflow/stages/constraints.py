"""Resolved implementation constraints translated through pad models."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping, Sequence

from chipflow.config.project import ProjectConfig
from chipflow.technologies.profile import ProcessProfile


@dataclass(frozen=True)
class ConstraintRow:
    id: str
    status: str
    message: str


@dataclass(frozen=True)
class ConstraintResult:
    text: str
    translation: dict[str, Any]
    rows: tuple[ConstraintRow, ...]

    @property
    def failed(self) -> bool:
        return any(row.status == "FAIL" for row in self.rows)

    @property
    def warned(self) -> bool:
        return any(row.status == "WARN" for row in self.rows)


def _port_name(name: str) -> str:
    return "{" + name + "}"


def _resolve_bit(
    port: str,
    design_ports: Mapping[str, Mapping[str, Any]],
    bit_index: Mapping[str, tuple[str, int | None]],
) -> tuple[str, int | None, str] | None:
    if port in bit_index:
        base, index = bit_index[port]
        return base, index, port
    base_candidate, separator, suffix = port.partition("[")
    if separator and suffix.endswith("]"):
        index_text = suffix[:-1]
        if index_text == "0" and base_candidate in design_ports and design_ports[base_candidate].get("width") == 1:
            return base_candidate, None, base_candidate
    return None


def build_constraints(
    project: ProjectConfig,
    profile: ProcessProfile,
    pad_plan: Mapping[str, Any],
    design_ports: Mapping[str, Mapping[str, Any]],
) -> ConstraintResult:
    """Create one SDC for placement, CTS and STA from resolved configuration.

    Board-level loads are translated into the load the selected output pad
    presents to the core; they are never applied directly to a core port.  Pad
    propagation delays are not extracted by this engine version, so board
    delays are carried to the core boundary with that limitation recorded.
    """
    bit_index: dict[str, tuple[str, int | None]] = {}
    for name, info in design_ports.items():
        width = info.get("width")
        bits = tuple(info.get("canonical_bits", ()))
        if type(width) is not int or len(bits) != width:
            raise ValueError(f"design port {name!r} is not structurally resolved")
        for index, bit in enumerate(bits):
            bit_index[bit] = (name, None if width == 1 else index)

    pads_by_bit: dict[str, Mapping[str, Any]] = {}
    for pad in pad_plan.get("pads", ()):
        if pad.get("kind") == "signal" and pad.get("port"):
            pads_by_bit[str(pad["port"])] = pad

    errors: list[str] = []
    warnings: list[str] = []
    translation: dict[str, Any] = {
        "schema_version": 1,
        "clock": {},
        "inputs": [],
        "outputs": [],
        "pad_delay_model": "not-extracted",
    }

    clock_port = design_ports.get(project.clock.port)
    if clock_port is None or clock_port.get("direction") != "input" or clock_port.get("width") != 1:
        errors.append(f"clock port {project.clock.port!r} must be a scalar input")
        clock_name = project.clock.port
    else:
        clock_name = project.clock.port
    translation["clock"] = {
        "port": clock_name,
        "period_ns": project.clock.period_ns,
        "waveform_ns": list(project.clock.waveform_ns),
        "transition_ns": project.clock.transition_ns,
        "uncertainty_ns": project.clock.uncertainty_ns,
    }

    lines: list[str] = [
        "# Generated by chipflow from the resolved project configuration.",
        "# Board loads are translated to pad/core quantities; see synthesis.json.",
        f"create_clock -name {clock_name} -period {project.clock.period_ns:.6f} "
        f"-waveform {{{project.clock.waveform_ns[0]:.6f} {project.clock.waveform_ns[1]:.6f}}} "
        f"[get_ports {_port_name(clock_name)}]",
        f"set_clock_uncertainty {project.clock.uncertainty_ns:.6f} [get_clocks {_port_name(clock_name)}]",
        f"set_input_transition {project.clock.transition_ns:.6f} [get_ports {_port_name(clock_name)}]",
    ]

    constrained_inputs: set[str] = set()
    constrained_outputs: set[str] = set()
    for delay in project.io.inputs:
        resolved = _resolve_bit(delay.port, design_ports, bit_index)
        if resolved is None:
            errors.append(f"io.inputs names unknown port bit {delay.port!r}")
            continue
        base, index, canonical = resolved
        if design_ports[base].get("direction") != "input":
            errors.append(f"io.inputs port {delay.port!r} is not a design input")
            continue
        pad = pads_by_bit.get(canonical)
        if pad is None:
            errors.append(f"input port bit {canonical!r} has no active pad slot")
            continue
        cell_name = pad.get("cell")
        cell = profile.pad_cells.get(cell_name)
        if cell is None or cell.direction != "input":
            errors.append(f"input pad for {canonical!r} has no qualified input cell")
            continue
        constrained_inputs.add(canonical)
        wrapper_name = base if index is None else f"{base}[{index}]"
        lines.append(f"set_input_delay -clock {_port_name(clock_name)} -min {delay.min_ns:.6f} [get_ports {_port_name(wrapper_name)}]")
        lines.append(f"set_input_delay -clock {_port_name(clock_name)} -max {delay.max_ns:.6f} [get_ports {_port_name(wrapper_name)}]")
        lines.append(
            f"set_driving_cell -lib_cell {cell_name} -pin {cell.core_pin} "
            f"[get_ports {_port_name(wrapper_name)}]"
        )
        lines.append(f"set_input_transition {project.clock.transition_ns:.6f} [get_ports {_port_name(wrapper_name)}]")
        translation["inputs"].append({
            "port": canonical,
            "wrapper_port": wrapper_name,
            "pad_cell": cell_name,
            "pad_core_pin": cell.core_pin,
            "board_min_ns": delay.min_ns,
            "board_max_ns": delay.max_ns,
            "core_min_ns": delay.min_ns,
            "core_max_ns": delay.max_ns,
            "max_core_load_pf": cell.max_core_load_pf,
            "pad_delay_ns": None,
        })

    for delay in project.io.outputs:
        resolved = _resolve_bit(delay.port, design_ports, bit_index)
        if resolved is None:
            errors.append(f"io.outputs names unknown port bit {delay.port!r}")
            continue
        base, index, canonical = resolved
        if design_ports[base].get("direction") != "output":
            errors.append(f"io.outputs port {delay.port!r} is not a design output")
            continue
        pad = pads_by_bit.get(canonical)
        if pad is None:
            errors.append(f"output port bit {canonical!r} has no active pad slot")
            continue
        cell_name = pad.get("cell")
        cell = profile.pad_cells.get(cell_name)
        if cell is None or cell.direction != "output":
            errors.append(f"output pad for {canonical!r} has no qualified output cell")
            continue
        board_load = delay.load_pf
        if board_load is None:
            errors.append(f"output port {canonical!r} has no board load; cannot evaluate the pad limit")
            continue
        if cell.max_pad_load_pf <= 0:
            errors.append(f"pad cell {cell_name} has no qualified maximum pad load")
            continue
        if board_load > cell.max_pad_load_pf:
            errors.append(
                f"output {canonical} board load {board_load:g} pF exceeds "
                f"{cell_name} limit {cell.max_pad_load_pf:g} pF"
            )
            continue
        core_load = cell.core_pin_capacitance_pf
        if core_load <= 0:
            errors.append(f"pad cell {cell_name} has no core-pin capacitance")
            continue
        constrained_outputs.add(canonical)
        wrapper_name = f"{base}_b" if index is None else f"{base}_b[{index}]"
        wrapper_decl = f"{base}_b" if design_ports[base].get("width") == 1 else f"{base}_b[{index}]"
        lines.append(f"set_load {core_load:.6f} [get_ports {_port_name(wrapper_decl)}]")
        lines.append(f"set_output_delay -clock {_port_name(clock_name)} -min {delay.min_ns:.6f} [get_ports {_port_name(wrapper_decl)}]")
        lines.append(f"set_output_delay -clock {_port_name(clock_name)} -max {delay.max_ns:.6f} [get_ports {_port_name(wrapper_decl)}]")
        translation["outputs"].append({
            "port": canonical,
            "wrapper_port": wrapper_name,
            "pad_cell": cell_name,
            "pad_core_pin": cell.core_pin,
            "board_load_pf": board_load,
            "pad_max_load_pf": cell.max_pad_load_pf,
            "core_load_pf": core_load,
            "board_min_ns": delay.min_ns,
            "board_max_ns": delay.max_ns,
            "core_min_ns": delay.min_ns,
            "core_max_ns": delay.max_ns,
            "pad_delay_ns": None,
        })

    expected_inputs = {
        bit
        for name, info in design_ports.items()
        if info.get("direction") == "input"
        for bit in info.get("canonical_bits", ())
        if bit != project.clock.port
    }
    expected_outputs = {
        bit
        for info in design_ports.values()
        if info.get("direction") == "output"
        for bit in info.get("canonical_bits", ())
    }
    if constrained_inputs != expected_inputs:
        errors.append(
            "input constraints do not cover design inputs: missing "
            + ", ".join(sorted(expected_inputs - constrained_inputs))
            + (" extra " + ", ".join(sorted(constrained_inputs - expected_inputs)) if constrained_inputs - expected_inputs else "")
        )
    if constrained_outputs != expected_outputs:
        errors.append(
            "output constraints do not cover design outputs: missing "
            + ", ".join(sorted(expected_outputs - constrained_outputs))
            + (" extra " + ", ".join(sorted(constrained_outputs - expected_outputs)) if constrained_outputs - expected_outputs else "")
        )
    if project.clock.port in constrained_inputs:
        errors.append("clock port must not carry a data input delay")
    warnings.append("pad propagation delays are not extracted; board delays pass to the core boundary unchanged")

    rows = (
        ConstraintRow(
            "synthesis.constraints.coverage",
            "FAIL" if errors else "PASS",
            "; ".join(errors) or f"{len(constrained_inputs)} input and {len(constrained_outputs)} output bits constrained",
        ),
        ConstraintRow(
            "synthesis.constraints.loads",
            "PASS" if not any("board load" in error for error in errors) else "FAIL",
            "every board load is within its pad limit",
        ),
        ConstraintRow(
            "synthesis.constraints.pad_delay",
            "WARN" if not errors else "PASS",
            "pad propagation delays are not extracted; board delays pass through unchanged",
        ),
    )
    lines.append("")
    return ConstraintResult(text="\n".join(lines), translation=translation, rows=rows)
